//! The generated server config and the scripts placed next to it.

use super::*;

/// Puts a value in quotes for a config line; refuses characters that would
/// end the line or start another command.
pub fn cfg_quote(value: &str, what: &str) -> Result<String> {
    if value.chars().any(|c| c.is_control() || c == '"' || c == '\\' || c == ';') {
        return Err(Error::Other(format!(
            "{what} must not contain quotes, backslashes, semicolons or line breaks."
        )));
    }
    Ok(format!("\"{value}\""))
}

pub fn valid_map(name: &str) -> bool {
    !name.is_empty()
        && name.len() <= 64
        && name.chars().all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || c == '_')
}

/// Checks the settings a person can type (names, password, map name).
pub fn validate_settings(s: &Settings) -> Result<()> {
    let official = Selection {
        map: content::Item {
            kind: content::Kind::OfficialMap,
            id: String::new(),
            name: s.map.clone(),
            title: String::new(),
            path: PathBuf::new(),
        },
        mod_item: None,
        more: Vec::new(),
    };
    if let Some(bad) = s.rotation.iter().find(|m| !valid_map(m)) {
        return Err(Error::Other(format!("\"{bad}\" in the rotation is not a valid map name.")));
    }
    if !s.mod_id.is_empty() && !s.mod_id.chars().all(|c| c.is_ascii_digit()) {
        return Err(Error::Other("The mod id must be a Steam Workshop number.".into()));
    }
    config_text(s, &official).map(|_| ())
}

/// Text of the generated config.
pub fn config_text(s: &Settings, sel: &Selection) -> Result<String> {
    let menu_players =
        cfg_quote(&crate::settings::normalize_players(&s.menu_players), "The list of menu players")?;
    let on = |b: bool| if b { 1 } else { 0 };
    let workshop_id = sel.workshop_id();
    let script_options = format!(
        "set bsm_menu \"{}\"\n\
         set bsm_menu_players {menu_players}\n\
         set bsm_god \"{}\"\n\
         set bsm_ammo \"{}\"\n\
         set bsm_start_points \"{}\"\n\
         set bsm_start_perks \"{}\"\n\
         set bsm_instakill \"{}\"\n\
         set bsm_double_points \"{}\"\n\
         set bsm_keep_perks \"{}\"\n\
         set bsm_scoreboard \"{}\"\n\
         set bsm_autosave \"{}\"\n\
         set bsm_autoload \"{}\"\n",
        on(s.menu),
        on(s.god_all),
        on(s.ammo_all),
        s.start_points,
        on(s.start_perks),
        on(s.instakill_all),
        on(s.double_points),
        on(s.keep_perks),
        on(s.scoreboard),
        on(s.autosave),
        if crate::saves::valid_slot(&s.continue_save) { s.continue_save.as_str() } else { "" }
    );
    if !valid_map(&s.map) {
        return Err(Error::Other(format!("\"{}\" is not a valid map name (example: zm_zod).", s.map)));
    }
    if s.server_name.trim().is_empty() {
        return Err(Error::Other("The server name is empty.".into()));
    }
    let name = cfg_quote(s.server_name.trim(), "The server name")?;
    let password = cfg_quote(&s.password, "The password")?;
    if s.password.contains(' ') {
        return Err(Error::Other("The password must not contain spaces.".into()));
    }
    let players = s.max_players.clamp(1, 8);
    let description = if s.password.is_empty() { "Zombies" } else { "Zombies (password protected)" };
    Ok(format!(
        "// Generated by Boiii Server Maker. This file is rewritten on every setup and start.\n\
         // Put your own extra settings in {CUSTOM_CFG_NAME} (same folder); it is never overwritten.\n\
         \n\
         set live_steam_server_name {name}\n\
         set live_steam_server_description \"{description}\"\n\
         \n\
         set com_maxclients \"{players}\"\n\
         set lobby_min_players \"1\"\n\
         set rcon_password \"\"\n\
         set g_password {password}\n\
         set sv_privateClients \"0\"\n\
         set sv_timeout \"30\"\n\
         set sv_reconnectlimit \"3\"\n\
         set sv_pure \"0\"\n\
         set sv_floodProtect \"1\"\n\
         set g_log \"boiii/games_zm.log\"\n\
         set g_logsync \"1\"\n\
         set sv_lobby_mode \"zm\"\n\
         set sv_skip_lobby \"1\"\n\
         set sv_lanonly \"0\"\n\
         \n\
         exec \"gamedata/gamesettings/zm/gamesettings_default.cfg\"\n\
         exec \"gamedata/configs/common/default_xboxlive.cfg\"\n\
         exec \"gamedata/gamesettings/zm/gamesettings_zclassic.cfg\"\n\
         \n\
         set cg_thirdPerson \"0\"\n\
         set g_deadChat \"0\"\n\
         set scr_firstGumFree \"1\"\n\
         \n\
         // Mod menu and start options (read by {menu_script})\n\
         {script_options}\
         \n\
         exec {CUSTOM_CFG_NAME}\n\
         \n\
         set workshop_id \"{workshop_id}\"\n\
         set sv_maprotation \"{rotation}\"\n\
         {rest}",
        rotation = sel.rotation_text(),
        rest =
            sel.rotation_rest().map(|r| format!("set sv_maprotationcurrent \"{r}\"\n")).unwrap_or_default(),
        menu_script = MENU_SCRIPT_REL.replace('\\', "/")
    ))
}

/// Writes or removes this tool's scripts in the server folder.
///
/// * The lobby script is written only when the folder has none.
/// * The menu script is there exactly while one of its options is on, so a
///   normal game runs without any extra script.
pub fn install_scripts(env: &Env, log: &dyn Fn(&str)) -> Result<()> {
    let lobby = env.server_dir.join(LOBBY_SCRIPT_REL);
    if !lobby.exists() || wiped_text(&lobby) {
        if let Some(parent) = lobby.parent() {
            io_ctx(fs::create_dir_all(parent), "create", parent)?;
        }
        io_ctx(fs::write(&lobby, LOBBY_SCRIPT), "write", &lobby)?;
        log("Lobby script added (lets the server load the chosen map directly).");
    }
    let menu = env.server_dir.join(MENU_SCRIPT_REL);
    if env.settings.any_script_option() {
        let current = fs::read_to_string(&menu).unwrap_or_default();
        if current != MENU_SCRIPT {
            if let Some(parent) = menu.parent() {
                io_ctx(fs::create_dir_all(parent), "create", parent)?;
            }
            io_ctx(fs::write(&menu, MENU_SCRIPT), "write", &menu)?;
        }
        log(&format!("Mod menu script in place: {}", menu.display()));
    } else if menu.exists() {
        io_ctx(fs::remove_file(&menu), "remove", &menu)?;
        log("Mod menu script removed (all its options are off).");
    }
    Ok(())
}
